func TestMaterializeNginxIncludeStdoutIsReadOnlyAndReproducible(t *testing.T) {
	root := nginxWorkerTempDir(t)
	configPath := filepath.Join(root, "sow.yaml")
	if err := os.WriteFile(configPath, []byte(testConfig), 0o600); err != nil {
		t.Fatal(err)
	}
	prepareNginxAssetRouteFixture(t, root, configPath, "latest")
	before := readMaterializationTree(t, root)
	render := func() (int, string, string) {
		var stdout, stderr bytes.Buffer
		code := Main([]string{"materialize", "latest", "--config", configPath, "--nginx-include", "-"}, &stdout, &stderr)
		return code, stdout.String(), stderr.String()
	}
	firstCode, first, firstErr := render()
	secondCode, second, secondErr := render()
	if firstCode != ExitOK || secondCode != ExitOK || firstErr != "" || secondErr != "" {
		t.Fatalf("first=(%d,%q) second=(%d,%q)", firstCode, firstErr, secondCode, secondErr)
	}
	if first != second {
		t.Fatal("identical render-only commands produced different stdout")
	}
	resolvedRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, wanted := range []string{
		"# Generated by sow from validated schema sow/v1",
		"location ^~ /asset/ {",
		"alias \"" + filepath.Join(resolvedRoot, "asset") + string(filepath.Separator) + "\";",
		"location / { return 404; }",
	} {
		if !strings.Contains(first, wanted) {
			t.Fatalf("stdout is missing %q:\n%s", wanted, first)
		}
	}
	if after := readMaterializationTree(t, root); !reflect.DeepEqual(before, after) {
		t.Fatalf("render-only mode mutated its admitted canonical/CAS fixture\nbefore=%v\nafter=%v", before, after)
	}
}

