func TestNginxCompatibilityAdmissionRootABARemainsBoundToOriginal(t *testing.T) {
	fixture := newFlatYUMCompatibilityFixture(t)
	workspace := filepath.Clean(filepath.Join(fixture.root, "..", "..", ".."))
	configPath := filepath.Join(workspace, "sow.yaml")
	if err := os.MkdirAll(filepath.Join(workspace, "yum", "infra", "el9", "x86_64"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(workspace, "files"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(configPath, []byte(nginxCompatibilityConfigYAML), 0o600); err != nil {
		t.Fatal(err)
	}
	var stdout, stderr bytes.Buffer
	if code := Main([]string{"init", "--config", configPath, "--workers", "1", "--chunk-entries", "2"}, &stdout, &stderr); code != ExitOK {
		t.Fatalf("init code=%d stdout=%s stderr=%s", code, stdout.String(), stderr.String())
	}
	cfg, err := config.Load(configPath, "")
	if err != nil {
		t.Fatal(err)
	}
	replacement := workspace + "-nginx-replacement"
	displaced := workspace + "-nginx-displaced"
	if err := os.Mkdir(replacement, 0o755); err != nil {
		t.Fatal(err)
	}
	marker := filepath.Join(replacement, "must-not-be-read-or-written")
	if err := os.WriteFile(marker, []byte("replacement B unchanged\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(replacement, 0o000); err != nil {
		t.Fatal(err)
	}
	swapped, restored := false, false
	t.Cleanup(func() {
		_ = os.Chmod(replacement, 0o755)
		if swapped && !restored {
			_ = os.Rename(workspace, replacement)
			_ = os.Rename(displaced, workspace)
		}
	})
	ctx := withNginxCompatibilityAdmissionHook(t.Context(), func(phase, projection string) error {
		if projection != "infra-legacy-x86-64" {
			return nil
		}
		switch phase {
		case "before-stage-audit":
			if err := os.Rename(workspace, displaced); err != nil {
				return err
			}
			if err := os.Rename(replacement, workspace); err != nil {
				_ = os.Rename(displaced, workspace)
				return err
			}
			swapped = true
		case "after-stage-audit":
			if err := os.Rename(workspace, replacement); err != nil {
				return err
			}
			if err := os.Rename(displaced, workspace); err != nil {
				_ = os.Rename(replacement, workspace)
				return err
			}
			restored = true
		}
		return nil
	})
	raw, active, err := admittedNginxCompatibility(ctx, cfg, cfg.Repos, "latest", workspace, commonFlags{workers: 1, chunk: 2})
	if err != nil || !swapped || !restored || !reflect.DeepEqual(raw, []string{"infra-legacy-x86-64"}) || len(active) != 0 {
		t.Fatalf("A->B->A admission raw=%v active=%v swapped=%t restored=%t err=%v", raw, active, swapped, restored, err)
	}
	if err := os.Chmod(replacement, 0o755); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(marker)
	if err != nil || string(body) != "replacement B unchanged\n" {
		t.Fatalf("replacement B changed or was consumed: body=%q err=%v", body, err)
	}
}

